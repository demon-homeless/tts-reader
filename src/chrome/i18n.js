function detectLocale() {
  try {
    const lang = (chrome.i18n.getUILanguage() || navigator.language || "en").toLowerCase();
    // Chrome uses "zh-CN", "en-US", "ja-JP", etc. Map to our locale keys.
    if (lang.startsWith("zh")) return "zh_CN";
    if (lang.startsWith("ja")) return "ja";
    if (lang.startsWith("ko")) return "ko";
    if (lang.startsWith("fr")) return "fr";
    if (lang.startsWith("de")) return "de";
    if (lang.startsWith("es")) return "es";
    if (lang.startsWith("ru")) return "ru";
    return "en";
  } catch {
    return "en";
  }
}

let _locale = detectLocale();
let _messages = I18N_LOCALES[_locale] || I18N_LOCALES.en;

const i18n = {
  get locale() {
    return _locale;
  },
  t(key) {
    return _messages[key] || I18N_LOCALES.en[key] || key;
  },
  /**
   * Apply i18n to elements with data-i18n attributes.
   * Usage in HTML: <label data-i18n="settings.provider">Provider</label>
   */
  apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const text = i18n.t(key);
      if (text !== key) {
        el.textContent = text;
      }
    });
    // Also apply to placeholder attributes
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const text = i18n.t(key);
      if (text !== key) {
        el.setAttribute("placeholder", text);
      }
    });
  },
};

// Export for use in other scripts
if (typeof module !== "undefined") module.exports = i18n;
if (typeof self !== "undefined") self.i18n = i18n;
